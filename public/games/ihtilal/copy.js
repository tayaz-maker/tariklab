export function fx(card, lang) {
  const tr = lang !== "en";
  const bits = (card.effect || []).map((op) => {
    if (op.op === "push") return tr ? `${labelDesk(op.desk, tr)} nüfuz +${op.n}` : `${labelDesk(op.desk, false)} presence +${op.n}`;
    if (op.op === "pull") return tr ? `${op.who === "self" ? "senin " : "rakip "}${labelDesk(op.desk, tr)} −${op.n}` : `${op.who === "self" ? "your " : "rival "}${labelDesk(op.desk, false)} −${op.n}`;
    if (op.op === "steal") return tr ? `çek ${labelDesk(op.desk, tr)} ${op.n}` : `steal ${labelDesk(op.desk, false)} ${op.n}`;
    if (op.op === "seal") return tr ? `mühür ${op.n > 0 ? "+" : ""}${op.n}` : `seal ${op.n > 0 ? "+" : ""}${op.n}`;
    if (op.op === "heat") return tr ? `ısı ${op.n > 0 ? "+" : ""}${op.n}` : `heat ${op.n > 0 ? "+" : ""}${op.n}`;
    if (op.op === "ink") return tr ? `mürekkep +${op.n}` : `ink +${op.n}`;
    if (op.op === "draw") return tr ? `${op.n} dosya çek` : `draw ${op.n} files`;
    if (op.op === "mill") return tr ? `rakip desteden ${op.n} dosya at` : `discard ${op.n} from rival deck`;
    if (op.op === "hukum") return tr ? `hüküm +${op.n}` : `ruling +${op.n}`;
    if (op.op === "protect") return tr ? `koru ${labelDesk(op.desk, tr)}` : `protect ${labelDesk(op.desk, false)}`;
    if (op.op === "unlock") return tr ? `kilit aç ${labelDesk(op.desk, tr)}` : `unlock ${labelDesk(op.desk, false)}`;
    if (op.op === "discard") return tr ? `rakip elden ${op.n} dosya at` : `discard ${op.n} from rival hand`;
    if (op.op === "peek") return tr ? "artçıya bak" : "peek aftershock";
    return op.op;
  });
  return bits.join(" · ");
}

export function labelDesk(id, tr) {
  const map = {
    sicil: tr ? "Sicil" : "Registry",
    kasa: tr ? "Kasa" : "Till",
    manset: tr ? "Manşet" : "Gazette",
    koridor: tr ? "Koridor" : "Corridor",
    nobet: tr ? "Nöbet" : "Watch",
    any: tr ? "her masa" : "any desk",
  };
  return map[id] || id;
}
