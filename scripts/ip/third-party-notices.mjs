// Writes docs/ip/THIRD_PARTY_NOTICES.md from docs/ip/client-packages.json and
// the installed packages' own license files. Run after `npm ci`:
//   node scripts/ip/third-party-notices.mjs
// The notices carry the license text each package ships; nothing is paraphrased.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const ALLOWED_LICENSES = new Set([
  "MIT",
  "ISC",
  "Apache-2.0",
  "0BSD",
  "BSD-2-Clause",
  "BSD-3-Clause",
]);

export function readPackage(root, name) {
  const dir = join(root, "node_modules", name);
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
  const author = typeof pkg.author === "string" ? pkg.author : pkg.author?.name;
  return {
    name,
    version: pkg.version,
    license: typeof pkg.license === "string" ? pkg.license : String(pkg.license?.type ?? "UNKNOWN"),
    repository: typeof pkg.repository === "string" ? pkg.repository : (pkg.repository?.url ?? ""),
    author: author ?? "",
    file: file ?? null,
    text: file ? readFileSync(join(dir, file), "utf8").trim() : null,
  };
}

export function render(packages) {
  const out = [
    "# Third-party notices",
    "",
    "Generated by `scripts/ip/third-party-notices.mjs` from `docs/ip/client-packages.json`. Do not edit by hand.",
    "",
    "These are the third-party packages whose code or CSS is shipped to the browser by the TarikLab portal.",
    "Static games under `public/games/` carry no third-party runtime code except: the JITEM runtime,",
    "which is built from the same stack (React, TanStack, Tailwind CSS; see its own build); and pixi.js,",
    "vendored as a static file (`public/vendor/pixi/`, not part of the portal's Rollup bundle) and lazily",
    "loaded only by games with a PixiJS map renderer. See docs/TARIKLAB_PIXIJS_MAP_STATUS.md for which",
    "games and the vendored file's exact path, version and hash.",
    "TarikLab uses no third-party fonts (system font stacks only), no audio, and no third-party map data.",
    "",
    "| Package | Version | License |",
    "|---|---|---|",
    ...packages.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`),
    "",
  ];
  for (const p of packages) {
    out.push(
      `## ${p.name} ${p.version}`,
      "",
      `License: ${p.license}${p.repository ? ` · Source: ${p.repository.replace(/^git\+/, "")}` : ""}`,
      "",
    );
    if (p.text) out.push("```text", p.text, "```", "");
    else
      out.push(
        `The published package ships no license file; its package.json declares ${p.license}` +
          (p.author ? ` and names ${p.author} as author.` : "."),
        "The full license text must be confirmed from the upstream repository before any store or offline distribution.",
        "",
      );
  }
  return out.join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const root = process.cwd();
  const { packages } = JSON.parse(readFileSync(join(root, "docs/ip/client-packages.json"), "utf8"));
  if (!existsSync(join(root, "node_modules"))) throw Error("Run npm ci first");
  const list = packages.map((n) => readPackage(root, n));
  const bad = list.filter((p) => !ALLOWED_LICENSES.has(p.license));
  if (bad.length)
    throw Error(
      "License outside the allowed set: " + bad.map((p) => `${p.name} (${p.license})`).join(", "),
    );
  writeFileSync(join(root, "docs/ip/THIRD_PARTY_NOTICES.md"), render(list));
  console.log(`${list.length} packages written`);
}
