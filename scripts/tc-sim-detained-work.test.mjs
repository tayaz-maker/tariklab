import test from 'node:test';
import assert from 'node:assert/strict';
import { createNewGame, SAVE_VERSION, validateState } from '../public/games/tc-sim/js/state.js';
import { applyWeeklyLifeLoad, getWeeklyLifeLoad, getMonthlyEmploymentIncome } from '../public/games/tc-sim/js/life.js';
import { saveGame, loadGame, migrateState } from '../public/games/tc-sim/js/save.js';

for (const version of [5, 6]) test(`V${version}: detained work pauses through reload and resumes at release`, () => {
  let s = createNewGame({seed:17});
  s.meta.saveVersion = version;
  const migrated = migrateState(s);
  assert.equal(migrated.ok, true);
  s = migrated.state;
  s.flags.risk = {detainedUntil:s.time.absoluteWeek + 2};
  const experience = structuredClone(s.career.jobFamilyExperience);
  const money = s.finances.balance;
  const load = getWeeklyLifeLoad(s);
  assert.equal(load.commute, 0);
  assert.equal(load.energy, load.education.energy);
  assert.equal(load.stress, load.education.stress);
  assert.equal(load.load, load.education.load);
  assert.equal(getMonthlyEmploymentIncome(s), 0);
  applyWeeklyLifeLoad(s);
  assert.deepEqual(s.career.jobFamilyExperience, experience);
  assert.equal(s.flags.socialInsurance?.coveredWeeks || 0, 0);
  assert.equal(s.finances.balance, money);
  const data = new Map();
  const storage = {getItem:k=>data.get(k) ?? null, setItem:(k,v)=>data.set(k,v)};
  assert.equal(saveGame(storage,s).ok,true);
  const loaded = loadGame(storage);
  assert.equal(loaded.ok,true);
  s = loaded.state;
  s.time.absoluteWeek++;
  applyWeeklyLifeLoad(s);
  assert.deepEqual(s.career.jobFamilyExperience, experience);
  assert.equal(s.flags.socialInsurance?.coveredWeeks || 0, 0);
  s.time.absoluteWeek++;
  assert.ok(getMonthlyEmploymentIncome(s) > 0);
  assert.ok(getWeeklyLifeLoad(s).load > load.load);
  applyWeeklyLifeLoad(s);
  assert.equal(Object.values(s.career.jobFamilyExperience).reduce((a,b)=>a+b,0), Object.values(experience).reduce((a,b)=>a+b,0)+1);
  assert.equal(s.flags.socialInsurance.coveredWeeks,1);
  applyWeeklyLifeLoad(s);
  assert.equal(s.flags.socialInsurance.coveredWeeks,1);
  assert.equal(s.finances.balance,money);
  assert.equal(validateState(s).ok,true);
  assert.equal(SAVE_VERSION,6);
});
