import type { EconomyState, EconomyView } from "./economy-types.ts";
import type { SocialState, SocialView } from "./social-types.ts";
import type { ProgressionState, ProgressionView } from "./progression-types.ts";
import type { MobilityState, MobilityView } from "./mobility-types.ts";
import type { LifeState, LifeView } from "./life-types.ts";
export type Point = { x: number; y: number };
export type Location = Point & { scene: string };
export type Profile = {
  name: string;
  appearance: number;
  background: "local" | "newcomer" | "graduate";
  attributes: { body: number; mind: number; social: number; discipline: number };
};
export type Person = {
  id: string;
  name: string;
  age: number;
  local: boolean;
  location: Location;
  destination: Point | null;
  path: Point[];
  homeId: string;
  householdId: string;
  jobId: string | null;
  employerId: string | null;
  goal: string;
  health: number;
  stamina: number;
  hunger: number;
  fatigue: number;
  debt: number;
  income: number;
  expenses: number;
  propertyIds: string[];
  skills: Record<string, number>;
  memories: string[];
  wanted: number;
  lastDecision: number;
  appearance: number;
  alive: boolean;
};
export type Player = Person & {
  profile: Profile;
  inventory: Record<string, number>;
  reputation: number;
  influence: number;
  vehicleId: string | null;
  shift: { id: string; businessId: string; endsAt: number; wage: number; order?: "retail" | "mechanic" | "done" } | null;
  blocking: boolean;
  attackUntil: number;
  cooldownUntil: number;
};
export type Building = {
  id: string;
  name: string;
  kind: string;
  x: number;
  y: number;
  w: number;
  h: number;
  height: number;
  color: number;
  door: Point;
  sign: string;
};
export type Job = {
  id: string;
  name: string;
  businessId: string;
  skill: string;
  wage: number;
  duration: number;
};
export type Business = {
  id: string;
  buildingId: string;
  ownerId: string;
  employees: string[];
  stock: Record<string, number>;
  prices: Record<string, number>;
  wage: number;
  status: "open" | "distressed" | "closed";
  sales: number;
};
export type Relation = {
  from: string;
  to: string;
  trust: number;
  affection: number;
  fear: number;
  resentment: number;
  lastContact: number;
};
export type SocietyEvent = {
  id: string;
  tick: number;
  minute: number;
  kind: string;
  actors: string[];
  targetId: string | null;
  text: string;
  visibility: "public" | "witnessed" | "private";
  witnesses: string[];
  causeId: string | null;
};
export type LedgerEntry = {
  id: string;
  tick: number;
  from: string;
  to: string;
  amount: number;
  reason: string;
};
export type Quest = {
  id: string;
  kind: string;
  title: string;
  description: string;
  issuerId: string;
  targetId: string;
  buildingId: string;
  sourceEvent: string;
  status: "offered" | "active" | "complete" | "failed" | "expired";
  reward: number;
  deadline: number;
  progress: number;
  required: number;
};
export type Vehicle = {
  id: string;
  location: Location;
  heading: number;
  speed: number;
  /** NPC cruise intent retained while a physical obstruction holds actual speed at zero. */
  resumeSpeed?: number;
  driverId: string | null;
  lane: number;
  progress: number;
  color: number;
};
export type Crime = {
  /** Optional for older saves and non-property cases. The loss survives use or restitution. */
  propertyLoss?: {
    businessId: string;
    kind: string;
    itemId: string;
    value: number;
    location: { x: number; y: number; scene: string };
    returnedTick: number | null;
  };
  id: string;
  offender: string;
  victim: string;
  witnesses: string[];
  evidence: string[];
  reported: boolean;
  status: "unreported" | "investigating" | "pursuit" | "resolved";
  tick: number;
  fine: number;
};
export type Household = {
  id: string;
  members: string[];
  homeId: string;
  rent: number;
  arrears: number;
};
export type WorldState = {
  economy: EconomyState;
  social: SocialState;
  progression: ProgressionState;
  mobility: MobilityState;
  life: LifeState;
  schemaVersion: number;
  engineVersion: string;
  seed: number;
  tick: number;
  minute: number;
  rng: number;
  nextId: number;
  player: Player;
  npcs: Person[];
  households: Household[];
  businesses: Business[];
  accounts: Record<string, number>;
  openingTotal: number;
  ledger: LedgerEntry[];
  ledgerCheckpoint: { count: number; balances: Record<string, number> };
  events: SocietyEvent[];
  eventCount: number;
  relations: Relation[];
  quests: Quest[];
  crimes: Crime[];
  vehicles: Vehicle[];
  processedCommands: string[];
  flags: Record<string, number | string | boolean>;
  notices: string[];
};
export type Command = { v: 1; id: string; type: string; args: Record<string, unknown> };
export type CommandResult = { ok: boolean; reason: string; events: string[] };
export type RenderProjection = {
  economy?: EconomyView;
  visualAgentLimit?: number;
  social?: SocialView;
  progression?: ProgressionView;
  mobility?: MobilityView;
  life?: LifeView;
  tick: number;
  minute: number;
  player: Player;
  npcs: Person[];
  vehicles: Vehicle[];
  businesses: Business[];
  quests: Quest[];
  events: SocietyEvent[];
  relations: Relation[];
  crimes?: Crime[];
  balance: number;
  notices: string[];
  population: number;
  simMs: number;
};
